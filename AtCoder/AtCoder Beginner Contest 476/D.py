n, m, k = list(map(int, input().split()))
x, y = list(map(int, input().split()))
A = [0] + list(map(int, input().split()))
B = [0] + list(map(int, input().split()))

A.sort()
B.sort()

for i in range(1, n + 1):
    A[i] += A[i - 1]

maxi = 0
for i in range(0, m + 1):
    y -= (B[i] + k - 1) // k
    x += (B[i] + k - 1) // k * k - B[i]
    # print(i, y, x)
    if y < 0:
        break
    rem = y * k + x
    l, r = 0, n
    while l <= r:
        mid = (l + r) // 2
        if A[mid] > rem:
            r = mid - 1
        else:
            l = mid + 1
    maxi = max(maxi, r + i)
print(maxi)

